// Writes sw.js with the full list of app files to pre-cache for offline use.
// Run after changing files: node scripts/gen-sw.mjs (a unit test checks it is up to date).
import fs from 'node:fs';
import path from 'node:path';
import { APP_VERSION } from '../src/version.js';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const walk = (dir) => fs.readdirSync(path.join(root, dir), { withFileTypes: true }).flatMap((d) => {
  const p = `${dir}/${d.name}`;
  return d.isDirectory() ? walk(p) : [p];
});
export function precacheList() {
  return ['index.html', 'manifest.webmanifest', ...['styles', 'src', 'data', 'vendor', 'assets'].flatMap(walk)]
    .filter((f) => !/\.(map|gitkeep|md)$|LICENSE$/.test(f) && !f.endsWith('/.gitkeep'))
    .sort();
}

export function swSource() {
  return `// Generated by scripts/gen-sw.mjs — do not edit by hand.
// Offline service worker: pre-caches every app file; a new version waits until the user taps "Update".
const VERSION = 'g5-${APP_VERSION}-${hash(JSON.stringify(precacheList()))}';
const FILES = ${JSON.stringify(['./', ...precacheList()], null, 0)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(VERSION).then((c) => c.addAll(FILES))); });
self.addEventListener('message', (e) => { if (e.data === 'skipWaiting') self.skipWaiting(); });
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== VERSION).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request)));
});
`;
}

function hash(s) { let h = 2166136261; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } return (h >>> 0).toString(36); }

if (process.argv[1] && process.argv[1].endsWith('gen-sw.mjs')) {
  fs.writeFileSync(path.join(root, 'sw.js'), swSource());
  console.log(`sw.js: ${precacheList().length} files`);
}
