export function meaningGroup(m) {
  return MEANING_GROUPS.findIndex((g) => g.includes(m));
}

/** Two meanings clash if they're identical or in the same group. */
export function meaningsClash(a, b) {
  if (a === b) return true;
  const ga = meaningGroup(a);
  return ga !== -1 && ga === meaningGroup(b);
}

